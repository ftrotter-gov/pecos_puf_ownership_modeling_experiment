"""Run the InLaw checks and save a dated markdown report.

By default the report is written ONLY when every check passes, so the
inlaw_tests_results_by_day/ directory stays a record of known-good runs. Pass
--force_save to record a failing run as well.

Usage:
    python save_inlaw_results.py                 # save only if all pass
    python save_inlaw_results.py --force_save    # save regardless
    python save_inlaw_results.py --tests-dir other_tests

The filename is inlaw-results-YYYY-MM-DD.md, so re-running on the same day
replaces that day's report.

Exit code is 0 only when every check passed, whether or not a report was saved.

Note this does not call InLaw.run_all(): that helper raises InlawError when a
check fails, which would deny --force_save the structured results it needs. The
discovery and execution loop below mirrors run_all() so the output matches what
`inlaw inlaw_tests` prints.
"""

from __future__ import annotations

import argparse
import inspect
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import sqlalchemy
from dotenv import load_dotenv
from dynaconf import Dynaconf
from inlaw import InLaw

REPO_ROOT = Path(__file__).resolve().parent
DEFAULT_TESTS_DIR = REPO_ROOT / "inlaw_tests"
RESULTS_DIR = REPO_ROOT / "inlaw_tests_results_by_day"

STATUS_ICON = {"PASS": "✅", "FAIL": "❌", "ERROR": "💥"}


def read_only_args(connection_url: str) -> dict:
    """Open DuckDB read-only; the checks never write."""
    if connection_url.startswith("duckdb:") and ":memory:" not in connection_url:
        return {"read_only": True}
    return {}


def discover_checks(tests_dir: Path) -> list[type[InLaw]]:
    """Find InLaw subclasses the same way the inlaw CLI does."""
    discovered: list[type[InLaw]] = []
    for python_file in sorted(tests_dir.glob("*.py")):
        if not python_file.name.startswith("__"):
            discovered.extend(InLaw.get_classes_from_file(python_file))
    # Preserve order while dropping duplicates.
    return list(dict.fromkeys(discovered))


def run_check(check_class: type[InLaw], engine, settings) -> dict:
    """Execute one check and normalize its outcome."""
    title = getattr(check_class, "title", check_class.__name__)
    try:
        parameters = inspect.signature(check_class.run).parameters
        if "settings" in parameters:
            outcome = check_class.run(engine, settings=settings)
        elif "config" in parameters:
            outcome = check_class.run(engine, config=settings)
        else:
            outcome = check_class.run(engine)

        if outcome is True:
            return {"test": title, "status": "PASS", "message": None}
        if isinstance(outcome, str):
            return {"test": title, "status": "FAIL", "message": outcome}
        raise TypeError(
            f"Invalid return type {type(outcome)}; expected bool or str"
        )
    except Exception as exception:  # noqa: BLE001 - report, do not crash the run
        return {
            "test": title,
            "status": "ERROR",
            "message": f"{check_class.__name__} Error: {exception}",
        }


def render_markdown(results: list[dict], counts: dict, run_timestamp: datetime) -> str:
    """Build the dated report."""
    summary = (
        f"Summary: {counts['passed']} passed · "
        f"{counts['failed']} failed · {counts['errors']} errors"
    )
    all_passed = counts["failed"] == 0 and counts["errors"] == 0

    lines = [
        f"# InLaw results — {run_timestamp:%Y-%m-%d}",
        "",
        f"**{summary}**",
        "",
        f"- Run at: {run_timestamp:%Y-%m-%d %H:%M:%S %Z}",
        f"- Outcome: {'all checks passed' if all_passed else 'one or more checks did not pass'}",
        "",
        "## Checks",
        "",
    ]

    for result in results:
        icon = STATUS_ICON.get(result["status"], "?")
        lines.append(f"- {icon} **{result['status']}** — {result['test']}")
        if result["message"]:
            lines.append(f"  - {result['message']}")

    if not all_passed:
        lines += [
            "",
            "## Not passing",
            "",
            "This report was saved with `--force_save`; it records a run that did",
            "not fully pass.",
            "",
        ]
        for result in results:
            if result["status"] != "PASS":
                lines.append(
                    f"- {STATUS_ICON[result['status']]} **{result['test']}**"
                )
                lines.append(f"  - {result['message']}")

    lines += [
        "",
        "---",
        "",
        "Generated by `save_inlaw_results.py`. Each check lives in its own file",
        "under `inlaw_tests/`; see `inlaw_tests/README.md` for what the baselines",
        "mean and when to update them.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Run the InLaw checks and save a dated markdown report."
    )
    parser.add_argument(
        "--force_save",
        action="store_true",
        help="Save the report even when checks fail or error.",
    )
    parser.add_argument(
        "--tests-dir",
        default=str(DEFAULT_TESTS_DIR),
        help=f"Directory of InLaw check files (default: {DEFAULT_TESTS_DIR.name}).",
    )
    arguments = parser.parse_args(argv)

    tests_dir = Path(arguments.tests_dir).resolve()
    if not tests_dir.is_dir():
        print(f"No such tests directory: {tests_dir}", file=sys.stderr)
        return 2

    load_dotenv(REPO_ROOT / ".env")
    connection_url = os.environ.get("INLAW_URL")
    if not connection_url:
        print(
            "INLAW_URL is not set. Copy the template first:\n"
            "    cp example.env .env",
            file=sys.stderr,
        )
        return 2

    check_classes = discover_checks(tests_dir)
    if not check_classes:
        print(f"No InLaw check classes found in {tests_dir}", file=sys.stderr)
        return 2

    engine = sqlalchemy.create_engine(
        connection_url, connect_args=read_only_args(connection_url)
    )
    settings = Dynaconf(environments=False, load_dotenv=True)

    results = [run_check(c, engine, settings) for c in check_classes]
    counts = {
        "passed": sum(r["status"] == "PASS" for r in results),
        "failed": sum(r["status"] == "FAIL" for r in results),
        "errors": sum(r["status"] == "ERROR" for r in results),
    }
    all_passed = counts["failed"] == 0 and counts["errors"] == 0

    summary = (
        f"Summary: {counts['passed']} passed · "
        f"{counts['failed']} failed · {counts['errors']} errors"
    )
    print("=" * 44)
    print(summary)
    for result in results:
        icon = STATUS_ICON.get(result["status"], "?")
        detail = f": {result['message']}" if result["message"] else ""
        print(f"▶ Running: {result['test']} {icon} {result['status']}{detail}")

    if all_passed or arguments.force_save:
        run_timestamp = datetime.now(timezone.utc).astimezone()
        RESULTS_DIR.mkdir(exist_ok=True)
        report_path = RESULTS_DIR / f"inlaw-results-{run_timestamp:%Y-%m-%d}.md"
        report_path.write_text(
            render_markdown(results, counts, run_timestamp), encoding="utf-8"
        )
        note = "" if all_passed else "  (forced: run did not fully pass)"
        print(f"\nSaved {report_path.relative_to(REPO_ROOT)}{note}")
    else:
        print(
            "\nNot saved: one or more checks did not pass. "
            "Re-run with --force_save to record this anyway."
        )

    return 0 if all_passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
